namespace {
using Byte = std::uint8_t;
using Bytes = std::vector<Byte>;
using prediction_probability::Options;
using prediction_probability::ProbabilityModel;

constexpr std::size_t kHeaderSize = 64;
constexpr std::uint64_t kMaxRawBytes = 16ULL * 1024 * 1024;
constexpr std::uint64_t kMaxFrameBytes = 64ULL * 1024 * 1024;
constexpr std::uint32_t kTotal = 65536;
constexpr std::uint32_t kHalf = 0x80000000u;
constexpr std::uint32_t kQuarter = 0x40000000u;
constexpr std::uint32_t kThreeQuarter = 0xc0000000u;

enum class Provider : Byte { Ppmd = 1, Dmc = 2, Paq = 3, Cmix = 4 };

std::uint64_t fnv64(const Byte* data, std::size_t size) {
  std::uint64_t value = 14695981039346656037ULL;
  for (std::size_t i = 0; i < size; ++i) {
    value ^= data[i];
    value *= 1099511628211ULL;
  }
  return value;
}
std::uint64_t fnv64(const Bytes& data) { return fnv64(data.data(), data.size()); }

void put16(Bytes& out, std::uint16_t value) {
  out.push_back(static_cast<Byte>(value));
  out.push_back(static_cast<Byte>(value >> 8));
}
void put32(Bytes& out, std::uint32_t value) {
  for (unsigned i = 0; i < 4; ++i) out.push_back(static_cast<Byte>(value >> (8 * i)));
}
void put64(Bytes& out, std::uint64_t value) {
  for (unsigned i = 0; i < 8; ++i) out.push_back(static_cast<Byte>(value >> (8 * i)));
}
std::uint16_t get16(const Bytes& in, std::size_t offset) {
  if (offset > in.size() || in.size() - offset < 2) throw std::runtime_error("truncated PEC1 header");
  return static_cast<std::uint16_t>(in[offset] | (std::uint16_t(in[offset + 1]) << 8));
}
std::uint32_t get32(const Bytes& in, std::size_t offset) {
  if (offset > in.size() || in.size() - offset < 4) throw std::runtime_error("truncated PEC1 header");
  std::uint32_t value = 0;
  for (unsigned i = 0; i < 4; ++i) value |= std::uint32_t(in[offset + i]) << (8 * i);
  return value;
}
std::uint64_t get64(const Bytes& in, std::size_t offset) {
  if (offset > in.size() || in.size() - offset < 8) throw std::runtime_error("truncated PEC1 header");
  std::uint64_t value = 0;
  for (unsigned i = 0; i < 8; ++i) value |= std::uint64_t(in[offset + i]) << (8 * i);
  return value;
}

struct BitWriter {
  Bytes data;
  unsigned used = 0;
  void put(unsigned bit) {
    if (used == 0) data.push_back(0);
    if (bit) data.back() |= static_cast<Byte>(1u << (7 - used));
    used = (used + 1) & 7;
  }
};

struct BitReader {
  const Bytes& data;
  std::size_t bit = 0;
  unsigned get() {
    if (bit >= data.size() * 8 + 32)
      throw std::runtime_error("arithmetic padding exhausted");
    const std::size_t index = bit++;
    return index < data.size() * 8
               ? (data[index / 8] >> (7 - (index & 7))) & 1u
               : 0;
  }
};

std::uint32_t one_frequency(double probability) {
  if (!(probability >= 0.0 && probability <= 1.0))
    throw std::runtime_error("invalid model probability");
  // Both events retain nonzero mass. The exact deterministic quantizer is part
  // of PEC1 and is regenerated by the cold decoder from the same model state.
  std::uint32_t result = 1 + static_cast<std::uint32_t>(probability * 65534.0);
  return result > 65535 ? 65535 : result;
}

Bytes encode_body(const Bytes& raw, const Options& options) {
  ProbabilityModel model(options);
  std::uint32_t low = 0, high = 0xffffffffu;
  std::uint64_t pending = 0;
  BitWriter writer;
  auto emit = [&](unsigned bit) {
    writer.put(bit);
    while (pending) {
      writer.put(bit ^ 1u);
      --pending;
    }
  };
  for (Byte byte : raw) {
    for (int shift = 7; shift >= 0; --shift) {
      const unsigned bit = (byte >> shift) & 1u;
      const std::uint32_t one = one_frequency(model.predict());
      const std::uint32_t zero = kTotal - one;
      const std::uint64_t range = std::uint64_t(high) - low + 1;
      const std::uint32_t split =
          low + static_cast<std::uint32_t>(range * zero / kTotal);
      if (split == low || split > high)
        throw std::runtime_error("probability interval underflow");
      if (bit) low = split;
      else high = split - 1;
      for (;;) {
        if (high < kHalf) emit(0);
        else if (low >= kHalf) {
          emit(1);
          low -= kHalf;
          high -= kHalf;
        } else if (low >= kQuarter && high < kThreeQuarter) {
          ++pending;
          low -= kQuarter;
          high -= kQuarter;
        } else {
          break;
        }
        low <<= 1;
        high = (high << 1) | 1u;
      }
      model.observe(bit);
    }
  }
  ++pending;
  emit(low >= kQuarter ? 1u : 0u);
  return writer.data;
}

Bytes decode_body(const Bytes& body, std::size_t length, const Options& options) {
  if (body.empty()) throw std::runtime_error("missing arithmetic termination");
  ProbabilityModel model(options);
  std::uint32_t low = 0, high = 0xffffffffu, code = 0;
  BitReader reader{body};
  for (unsigned i = 0; i < 32; ++i) code = (code << 1) | reader.get();
  Bytes raw;
  raw.reserve(length);
  for (std::size_t index = 0; index < length; ++index) {
    Byte byte = 0;
    for (unsigned j = 0; j < 8; ++j) {
      if (code < low || code > high)
        throw std::runtime_error("arithmetic code outside interval");
      const std::uint32_t one = one_frequency(model.predict());
      const std::uint32_t zero = kTotal - one;
      const std::uint64_t range = std::uint64_t(high) - low + 1;
      const std::uint32_t split =
          low + static_cast<std::uint32_t>(range * zero / kTotal);
      if (split == low || split > high)
        throw std::runtime_error("probability interval underflow");
      const unsigned bit = code >= split ? 1u : 0u;
      if (bit) low = split;
      else high = split - 1;
      for (;;) {
        if (high < kHalf) {
        } else if (low >= kHalf) {
          low -= kHalf;
          high -= kHalf;
          code -= kHalf;
        } else if (low >= kQuarter && high < kThreeQuarter) {
          low -= kQuarter;
          high -= kQuarter;
          code -= kQuarter;
        } else {
          break;
        }
        low <<= 1;
        high = (high << 1) | 1u;
        code = (code << 1) | reader.get();
      }
      byte = static_cast<Byte>((byte << 1) | bit);
      model.observe(bit);
    }
    raw.push_back(byte);
  }
  return raw;
}

Provider provider_code(const std::string& provider) {
  if (provider == "ppmd") return Provider::Ppmd;
  if (provider == "dmc") return Provider::Dmc;
  if (provider == "paq") return Provider::Paq;
  if (provider == "cmix") return Provider::Cmix;
  throw std::runtime_error("provider must be ppmd, dmc, paq, or cmix");
}
std::string provider_name(Provider provider) {
  switch (provider) {
    case Provider::Ppmd: return "ppmd";
    case Provider::Dmc: return "dmc";
    case Provider::Paq: return "paq";
    case Provider::Cmix: return "cmix";
  }
  throw std::runtime_error("unknown PEC1 provider");
}

Bytes frame(const Bytes& raw, const Options& options) {
  if (raw.size() > kMaxRawBytes) throw std::runtime_error("raw input exceeds 16 MiB limit");
  prediction_probability::validate_options(options);
  const Provider provider = provider_code(options.provider);
  const Bytes body = encode_body(raw, options);
  Bytes out{'P', 'E', 'C', '1', 1, static_cast<Byte>(provider)};
  put16(out, 1);  // flags: MSB-first binary events and fixed 16-bit quantizer.
  out.push_back(provider == Provider::Ppmd ? static_cast<Byte>(options.ppmd_order) : 0);
  out.push_back(provider == Provider::Paq ? static_cast<Byte>(options.paq_level) : 0);
  put16(out, 0);
  put32(out, provider == Provider::Ppmd ? options.ppmd_memory_mib : 0);
  put32(out, provider == Provider::Dmc ? 65536 : 0);
  put32(out, provider == Provider::Dmc ? 1024 : 0);
  put64(out, raw.size());
  put64(out, body.size());
  put64(out, fnv64(raw));
  put64(out, fnv64(body));
  if (out.size() != 56) throw std::runtime_error("internal PEC1 header size error");
  put64(out, fnv64(out));
  out.insert(out.end(), body.begin(), body.end());
  return out;
}

struct Parsed {
  Options options;
  std::size_t raw_length = 0;
  Bytes body;
  std::uint64_t raw_hash = 0;
};

Parsed parse(const Bytes& encoded, bool allow_large_memory) {
  if (encoded.size() < kHeaderSize || std::memcmp(encoded.data(), "PEC1", 4) != 0)
    throw std::runtime_error("invalid PEC1 frame magic");
  if (encoded[4] != 1 || get16(encoded, 6) != 1 || get16(encoded, 10) != 0)
    throw std::runtime_error("unsupported PEC1 version, flags, or reserved fields");
  if (get64(encoded, 56) != fnv64(encoded.data(), 56))
    throw std::runtime_error("PEC1 header checksum mismatch");
  const auto provider_value = static_cast<Provider>(encoded[5]);
  Options options;
  options.provider = provider_name(provider_value);
  options.allow_large_memory = allow_large_memory;
  const unsigned order = encoded[8], paq_level = encoded[9];
  const std::uint32_t memory = get32(encoded, 12);
  const std::uint32_t nodes = get32(encoded, 16);
  const std::uint32_t threshold = get32(encoded, 20);
  if (provider_value == Provider::Ppmd) {
    if (paq_level || nodes || threshold) throw std::runtime_error("invalid PPMd PEC1 parameters");
    options.ppmd_order = order;
    options.ppmd_memory_mib = memory;
  } else if (provider_value == Provider::Dmc) {
    if (order || paq_level || memory || nodes != 65536 || threshold != 1024)
      throw std::runtime_error("invalid DMC PEC1 parameters");
  } else if (provider_value == Provider::Paq) {
    if (order || memory || nodes || threshold) throw std::runtime_error("invalid PAQ PEC1 parameters");
    options.paq_level = paq_level;
  } else if (provider_value == Provider::Cmix) {
    if (order || paq_level || memory || nodes || threshold)
      throw std::runtime_error("invalid cmix PEC1 parameters");
    if (!allow_large_memory)
      throw std::runtime_error("cmix PEC1 decode requires --allow-large-memory");
  }
  prediction_probability::validate_options(options);
  const std::uint64_t raw_length = get64(encoded, 24);
  const std::uint64_t body_length = get64(encoded, 32);
  if (raw_length > kMaxRawBytes) throw std::runtime_error("decoded output exceeds 16 MiB limit");
  if (body_length != encoded.size() - kHeaderSize)
    throw std::runtime_error("truncated or trailing PEC1 body");
  Bytes body(encoded.begin() + kHeaderSize, encoded.end());
  if (fnv64(body) != get64(encoded, 48)) throw std::runtime_error("PEC1 body checksum mismatch");
  return {options, static_cast<std::size_t>(raw_length), std::move(body), get64(encoded, 40)};
}

Bytes unframe(const Bytes& encoded, bool allow_large_memory) {
  Parsed parsed = parse(encoded, allow_large_memory);
  Bytes raw = decode_body(parsed.body, parsed.raw_length, parsed.options);
  if (fnv64(raw) != parsed.raw_hash) throw std::runtime_error("PEC1 decoded checksum mismatch");
  return raw;
}

Bytes read_stdin(std::uint64_t limit) {
  Bytes result;
  std::array<char, 65536> buffer{};
  while (std::cin) {
    std::cin.read(buffer.data(), buffer.size());
    const std::streamsize count = std::cin.gcount();
    if (count < 0 || result.size() + static_cast<std::size_t>(count) > limit)
      throw std::runtime_error("input exceeds bounded PEC1 limit");
    result.insert(result.end(), buffer.data(), buffer.data() + count);
  }
  if (!std::cin.eof()) throw std::runtime_error("stdin read failed");
  return result;
}

unsigned parse_unsigned(const char* text) {
  std::string value(text);
  if (value.empty() || value.find_first_not_of("0123456789") != std::string::npos)
    throw std::runtime_error("option values must be unsigned decimal integers");
  const unsigned long parsed = std::stoul(value);
  if (parsed > std::numeric_limits<unsigned>::max()) throw std::runtime_error("option too large");
  return static_cast<unsigned>(parsed);
}

struct Command {
  bool decode = false;
  Options options;
};

Command parse_command(int argc, char** argv) {
  if (argc < 2) throw std::runtime_error(
      "usage: prediction_entropy_codec_cli encode PROVIDER [options] | decode [--allow-large-memory]");
  Command result;
  int index = 2;
  const std::string mode = argv[1];
  if (mode == "encode") {
    if (argc < 3) throw std::runtime_error("encode requires provider");
    result.options.provider = argv[2];
    index = 3;
  } else if (mode == "decode") {
    result.decode = true;
  } else {
    throw std::runtime_error("command must be encode or decode");
  }
  for (; index < argc; ++index) {
    const std::string key = argv[index];
    if (key == "--allow-large-memory") {
      result.options.allow_large_memory = true;
      continue;
    }
    if (result.decode) throw std::runtime_error("decode accepts only --allow-large-memory");
    if (++index >= argc) throw std::runtime_error("missing option value");
    const unsigned value = parse_unsigned(argv[index]);
    if (key == "--ppmd-order") result.options.ppmd_order = value;
    else if (key == "--ppmd-memory-mib") result.options.ppmd_memory_mib = value;
    else if (key == "--paq-level") result.options.paq_level = value;
    else throw std::runtime_error("unknown option: " + key);
  }
  if (!result.decode) prediction_probability::validate_options(result.options);
  return result;
}
}  // namespace

int main(int argc, char** argv) {
  try {
    std::ios::sync_with_stdio(false);
    const Command command = parse_command(argc, argv);
    const Bytes input = read_stdin(command.decode ? kMaxFrameBytes : kMaxRawBytes);
    const Bytes output = command.decode
                             ? unframe(input, command.options.allow_large_memory)
                             : frame(input, command.options);
    std::cout.write(reinterpret_cast<const char*>(output.data()),
                    static_cast<std::streamsize>(output.size()));
    if (!std::cout) throw std::runtime_error("stdout write failed");
    return 0;
  } catch (const std::exception& error) {
    std::cerr << "prediction_entropy_codec: " << error.what() << '\n';
    return 2;
  }
}
