def main() -> None:
    sources_path = OUT_DIR / "research_algo_sources.csv"
    with sources_path.open("w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["paper", "raw_github_url"])
        w.writerows(SOURCES)

    classified_path = OUT_DIR / "research_algo_repos_classified.csv"
    fields = [
        "repo_slug",
        "algorithm_name",
        "clone_url",
        "related_papers",
        "lossy_lossless",
        "language",
        "data_types",
        "benchmark_category",
        "submodule",
        "submodule_path",
        "notes",
    ]
    with classified_path.open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        for row in CLASSIFIED:
            w.writerow(row)

    print(f"Wrote {len(SOURCES)} rows -> {sources_path}")
    print(f"Wrote {len(CLASSIFIED)} rows -> {classified_path}")


if __name__ == "__main__":
    main()
