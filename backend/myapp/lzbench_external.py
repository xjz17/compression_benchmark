logger = logging.getLogger(__name__)

REPORT_FIELDS = (
    "column_index",
    "algorithm",
    "originalSize",
    "compressedSize",
    "compressionTime",
    "decompressionTime",
    "isLossy",
    "lossRate",
)


def lzbench_bench_enabled() -> bool:
    # lzbench CLI backfill is intentionally disabled. Catalog byte-codec rows are
    # generated by ``native_lz_family`` in Python/C++/Java so no benchmark path
    # shells out to the external lzbench binary.
    return False


def allowlist_wants_lzbench() -> bool:
    """When ``WEB_COMPRESSION_RUN_ALGORITHMS`` is set, skip lzbench unless a catalog row is requested."""
    raw = os.environ.get("WEB_COMPRESSION_RUN_ALGORITHMS", "").strip()
    if not raw:
        return True
    from .lzbench_codec_catalog import is_lzbench_catalog_algorithm
    from .native_lz_family import NATIVE_LZ_FAMILY_ALGORITHMS

    native = set(NATIVE_LZ_FAMILY_ALGORITHMS)
    names = [part.strip() for part in raw.split(",") if part.strip()]
    for name in names:
        canonical = name[len("lzbench_") :] if name.startswith("lzbench_") else name
        if canonical in native:
            continue
        if is_lzbench_catalog_algorithm(name):
            return True
    return False


def lzbench_selectors() -> str:
    override = os.environ.get("WEB_COMPRESSION_LZBENCH_E", "").strip()
    if override:
        return override
    return "/".join(build_lzbench_selector(entry) for entry in LZBENCH_CODEC_ENTRIES)


def _lzbench_isolated_runs() -> bool:
    flag = os.environ.get("WEB_COMPRESSION_LZBENCH_ISOLATED", "").strip().lower()
    if flag in ("0", "false", "no", "off"):
        return False
    if flag in ("1", "true", "yes", "on"):
        return True
    return False


def _lzbench_timeout_sec() -> int | None:
    timeout_raw = os.environ.get("WEB_COMPRESSION_LZBENCH_TIMEOUT_SEC", "0").strip()
    try:
        timeout = int(timeout_raw)
    except ValueError:
        timeout = 0
    return None if timeout <= 0 else timeout


def column_bytes_from_series(data_type: str, series: pd.Series) -> bytes | None:
    if data_type == "string":
        parts: list[bytes] = []
        for cell in series:
            parts.append(_normalize_string_cell(cell).encode("utf-8"))
        out = b"".join(parts)
        return out if out else None
    if data_type == "int":
        values: list[int] = []
        for cell in series:
            v = _parse_int_cell_strict(cell)
            if v is not None:
                values.append(v)
        return pack_int64_le(values) if values else None
    if data_type == "float":
        values = []
        for cell in series:
            v = _parse_float_cell_strict(cell)
            if v is not None:
                values.append(v)
        return pack_float64_le(values) if values else None
    raise ValueError(data_type)


def column_indexes_for_dtype(column_info_path: str, data_type: str) -> list[int]:
    wanted = benchmark_dtype_logical_aliases(data_type)
    out: list[int] = []
    seen: set[int] = set()
    for row in load_column_info_rows(column_info_path):
        logical = str(row.get("logical_type", "")).strip().lower()
        if logical not in wanted:
            continue
        try:
            idx = int(row.get("column_index"))
        except (TypeError, ValueError):
            continue
        if idx in seen:
            continue
        seen.add(idx)
        out.append(idx)
    return sorted(out)


def _parse_lzbench_stdout(stdout: str) -> list[dict]:
    """Parse lzbench ``-o4`` CSV lines into benchmark rows (ns timings)."""
    rows: list[dict] = []
    lines = [ln.strip() for ln in (stdout or "").splitlines() if ln.strip()]
    if len(lines) < 2:
        return rows
    for line in lines[1:]:
        parts = line.split(",")
        if len(parts) < 6:
            continue
        name = parts[0].strip()
        if is_lzbench_selector_garbage_algorithm(name):
            continue
        try:
            c_us = int(float(parts[1]))
            d_us = int(float(parts[2]))
            orig = int(float(parts[3]))
            comp = int(float(parts[4]))
        except (TypeError, ValueError):
            continue
        if d_us <= 0 or orig <= 0:
            continue
        algo = lzbench_output_to_algorithm_key(name)
        if not algo or algo not in all_catalog_algorithm_keys():
            continue
        rows.append(
            {
                "algorithm": algo,
                "originalSize": orig,
                "compressedSize": comp,
                "compressionTime": c_us * 1000,
                "decompressionTime": d_us * 1000,
                "isLossy": 0,
                "lossRate": 0.0,
            }
        )
    return rows


def _merge_lzbench_rows(existing: list[dict], new_rows: Iterable[dict]) -> list[dict]:
    by_algo: dict[str, dict] = {str(r["algorithm"]): r for r in existing if r.get("algorithm")}
    for row in new_rows:
        algo = str(row.get("algorithm", "")).strip()
        if algo:
            by_algo[algo] = row
    return sorted(by_algo.values(), key=lambda r: str(r["algorithm"]))


def _run_lzbench_selector_once(
    payload_path: str,
    exe: Path,
    selector: str,
    *,
    timeout: int | None,
) -> list[dict]:
    cmd = [
        str(exe),
        "-o4",
        "-z",
        "-qq",
        "-t0,0",
        "-i1,1",
        f"-e{selector}",
        payload_path,
    ]
    try:
        proc = subprocess.run(
            cmd,
            capture_output=True,
            text=True,
            timeout=timeout,
            cwd=str(repo_root()),
        )
    except subprocess.TimeoutExpired:
        logger.warning("lzbench timed out for selector %s", selector[:80])
        return []

    rows = _parse_lzbench_stdout(proc.stdout or "")
    if proc.returncode != 0:
        detail = (proc.stderr or proc.stdout or "").strip()
        if rows:
            logger.warning(
                "lzbench selector %s exited %s; kept %d row(s). %s",
                selector[:80],
                proc.returncode,
                len(rows),
                detail[:400],
            )
        else:
            logger.warning(
                "lzbench selector %s failed (code %s). %s",
                selector[:80],
                proc.returncode,
                detail[:400],
            )
    return rows


def _entries_missing_rows(rows: list[dict]) -> list:
    got = {str(r.get("algorithm", "")).strip() for r in rows}
    missing = []
    for entry in LZBENCH_CODEC_ENTRIES:
        keys = entry_algorithm_keys(entry)
        if keys and not any(k in got for k in keys):
            missing.append(entry)
    return missing


def _run_lzbench_on_bytes(payload: bytes, exe: Path) -> list[dict]:
    """Return parsed rows: algorithm, originalSize, compressedSize, compressionTime, decompressionTime (ns).

    One failing codec must not discard others: parse stdout even on non-zero exit, then retry
    only catalog entries that produced no rows (e.g. tornado on high-entropy float bytes).
    Set ``WEB_COMPRESSION_LZBENCH_ISOLATED=1`` to run each catalog entry in its own subprocess.
    """
    if not allowlist_wants_lzbench():
        return []
    timeout = _lzbench_timeout_sec()
    with tempfile.NamedTemporaryFile(suffix=".bin", delete=False) as tmp:
        tmp.write(payload)
        tmp_path = tmp.name

    rows: list[dict] = []
    try:
        if _lzbench_isolated_runs():
            for selector in iter_lzbench_selector_batches(lzbench_selectors()):
                rows = _merge_lzbench_rows(
                    rows,
                    _run_lzbench_selector_once(tmp_path, exe, selector, timeout=timeout),
                )
            return rows

        combined = lzbench_selectors()
        rows = _run_lzbench_selector_once(tmp_path, exe, combined, timeout=timeout)
        for entry in _entries_missing_rows(rows):
            selector = build_lzbench_selector(entry)
            rows = _merge_lzbench_rows(
                rows,
                _run_lzbench_selector_once(tmp_path, exe, selector, timeout=timeout),
            )
        return rows
    finally:
        try:
            os.unlink(tmp_path)
        except OSError:
            pass


def accumulate_lzbench_column_byte_data(
    column_byte_data: Sequence[bytes],
    record_fn: Callable[..., None],
    should_run: Callable[[str], bool],
) -> None:
    """Run lzbench on each patch ``column_byte_data`` entry; merge via ``record_fn``."""
    if not lzbench_bench_enabled():
        return
    exe = lzbench_executable_path()
    if exe is None:
        return
    for payload in column_byte_data:
        if not payload:
            continue
        for row in _run_lzbench_on_bytes(payload, exe):
            algo = str(row.get("algorithm", "")).strip()
            if not algo or not should_run(algo):
                continue
            record_fn(
                algo,
                int(row["originalSize"]),
                int(row["compressedSize"]),
                int(row["compressionTime"]),
                int(row["decompressionTime"]),
            )


def _iter_series_patches(series: pd.Series, patch_rows: int):
    """Yield consecutive slices of at most ``patch_rows`` cells (same limit as Java/C++/Python patch bench)."""
    if patch_rows <= 0:
        patch_rows = patch_row_limit()
    n = len(series)
    for start in range(0, n, patch_rows):
        yield series.iloc[start : start + patch_rows]


def _aggregate_lzbench_patch_rows(patch_results: Sequence[Sequence[dict]]) -> list[dict]:
    """
    Sum ``originalSize`` / ``compressedSize`` / times across patches.
    Only algorithms present in every patch are kept (partial patch failure drops the column).
    """
    if not patch_results:
        return []
    if any(not patch for patch in patch_results):
        return []

    n_patches = len(patch_results)
    totals: dict[str, dict[str, int]] = {}
    counts: dict[str, int] = {}

    for patch_rows in patch_results:
        seen: set[str] = set()
        for row in patch_rows:
            algo = str(row.get("algorithm", "")).strip()
            if not algo:
                continue
            seen.add(algo)
            bucket = totals.setdefault(
                algo,
                {
                    "originalSize": 0,
                    "compressedSize": 0,
                    "compressionTime": 0,
                    "decompressionTime": 0,
                },
            )
            bucket["originalSize"] += int(row.get("originalSize", 0) or 0)
            bucket["compressedSize"] += int(row.get("compressedSize", 0) or 0)
            bucket["compressionTime"] += int(row.get("compressionTime", 0) or 0)
            bucket["decompressionTime"] += int(row.get("decompressionTime", 0) or 0)
            counts[algo] = counts.get(algo, 0) + 1

        for algo in totals:
            if algo not in seen:
                counts[algo] = counts.get(algo, 0)

    out: list[dict] = []
    for algo, bucket in totals.items():
        if counts.get(algo, 0) != n_patches:
            continue
        if bucket["originalSize"] <= 0 or bucket["decompressionTime"] <= 0:
            continue
        out.append(
            {
                "algorithm": algo,
                "originalSize": bucket["originalSize"],
                "compressedSize": bucket["compressedSize"],
                "compressionTime": bucket["compressionTime"],
                "decompressionTime": bucket["decompressionTime"],
                "isLossy": 0,
                "lossRate": 0.0,
            }
        )
    out.sort(key=lambda r: str(r["algorithm"]))
    return out


def _run_lzbench_on_series_patches(
    series: pd.Series,
    data_type: str,
    exe: Path,
    *,
    patch_rows: int | None = None,
) -> list[dict]:
    """Run lzbench on ``WEB_COMPRESSION_CSV_PATCH_ROWS``-sized chunks and aggregate."""
    limit = patch_row_limit() if patch_rows is None else int(patch_rows)
    if limit <= 0:
        limit = patch_row_limit()

    patch_results: list[list[dict]] = []
    for chunk in _iter_series_patches(series, limit):
        payload = column_bytes_from_series(data_type, chunk)
        if not payload:
            logger.warning("lzbench patch skipped: empty payload for dtype=%s", data_type)
            return []
        rows = _run_lzbench_on_bytes(payload, exe)
        if not rows:
            logger.warning(
                "lzbench patch failed for dtype=%s (%d-byte chunk)",
                data_type,
                len(payload),
            )
            return []
        patch_results.append(rows)

    if not patch_results:
        return []

    return _aggregate_lzbench_patch_rows(patch_results)


def _read_report_rows(report_path: str) -> list[dict]:
    if not os.path.isfile(report_path):
        return []
    with open(report_path, "r", encoding="utf-8", newline="") as handle:
        return list(csv.DictReader(handle))


def _write_report_rows(report_path: str, rows: list[dict]) -> None:
    report_path = str(report_path)
    os.makedirs(os.path.dirname(report_path) or ".", exist_ok=True)
    with open(report_path, "w", encoding="utf-8", newline="\n") as handle:
        writer = csv.DictWriter(handle, fieldnames=REPORT_FIELDS, lineterminator="\n")
        writer.writeheader()
        for row in rows:
            writer.writerow(
                {
                    "column_index": row.get("column_index"),
                    "algorithm": row.get("algorithm"),
                    "originalSize": row.get("originalSize"),
                    "compressedSize": row.get("compressedSize"),
                    "compressionTime": row.get("compressionTime"),
                    "decompressionTime": row.get("decompressionTime"),
                    "isLossy": row.get("isLossy", 0),
                    "lossRate": format_loss_rate_csv(float(row.get("lossRate", 0) or 0)),
                }
            )


def _strip_lzbench_rows(rows: list[dict]) -> list[dict]:
    """Remove every lzbench row (canonical keys, raw stdout names, and selector garbage)."""
    kept: list[dict] = []
    for row in rows:
        algo = str(row.get("algorithm", "")).strip()
        if not algo or is_lzbench_report_row_algorithm(algo):
            continue
        kept.append(row)
    return kept


def _append_lzbench_rows_to_one_report(report_path: str, new_rows: Iterable[dict]) -> int:
    existing = _read_report_rows(report_path)
    merged = _strip_lzbench_rows(existing)
    present = {
        (int(r.get("column_index", -1)), str(r.get("algorithm", "")).strip())
        for r in merged
        if str(r.get("algorithm", "")).strip()
    }
    added = 0
    for row in new_rows:
        key = (int(row["column_index"]), str(row["algorithm"]))
        if key in present:
            continue
        merged.append(row)
        present.add(key)
        added += 1
    if not added and len(merged) == len(existing):
        return 0
    sanitized = sanitize_compression_report_dataframe(pd.DataFrame(merged))
    if sanitized.empty:
        return 0
    _write_report_rows(report_path, sanitized.to_dict(orient="records"))
    return added


def append_lzbench_rows_to_reports(
    report_paths: Sequence[str],
    *,
    master_csv: str,
    column_info_path: str,
    data_type: str,
) -> int:
    """Backfill lzbench rows by re-streaming master CSV in patch chunks (merge script only)."""
    if not lzbench_bench_enabled():
        return 0
    exe = lzbench_executable_path()
    if exe is None:
        logger.info("lzbench skipped: binary not found")
        return 0

    col_indexes = column_indexes_for_dtype(column_info_path, data_type)
    if not col_indexes:
        return 0

    patch_rows = patch_row_limit()
    raw = pd.read_csv(master_csv)
    all_stamped: list[dict] = []
    for col_idx in col_indexes:
        if col_idx < 0 or col_idx >= raw.shape[1]:
            continue
        bench_rows = _run_lzbench_on_series_patches(
            raw.iloc[:, col_idx],
            data_type,
            exe,
            patch_rows=patch_rows,
        )
        if not bench_rows:
            continue
        all_stamped.extend({**row, "column_index": int(col_idx)} for row in bench_rows)

    if not all_stamped:
        return 0

    total_added = 0
    for path in report_paths:
        total_added += _append_lzbench_rows_to_one_report(path, all_stamped)
    if total_added:
        logger.info(
            "lzbench: merged %s row(s) into %d report(s) for %s",
            total_added,
            len(report_paths),
            data_type,
        )
    return total_added
