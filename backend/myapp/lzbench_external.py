"""Disabled legacy ``lzbench`` CLI helpers for byte-codec rows.

Runtime benchmark rows are emitted by ``native_lz_family`` in Python/C++/Java.
This module remains only for old imports and backfill scripts; its public entry
points do not run the external ``lzbench`` subprocess.
"""

